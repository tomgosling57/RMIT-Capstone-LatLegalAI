"""
PDF type detector for classifying PDF documents as digital, scanned, or hybrid.

A frontend-adapted port of the backend's ``pdf_type_detector``
(``backend/src/services/parsers/pdf_type_detector.py``) for use in the
Streamlit environment.

The detection pipeline consists of three stages:

1. **Stage 1 — /Image XObject count**: Counts image XObjects in the PDF's
   page resources. A high image-to-page ratio suggests scanned content.
2. **Stage 2 — Text extraction sampling**: Attempts to extract text from a
   sample of pages using ``pdfplumber``. Pages yielding meaningful text
   indicate digital content.
3. **Stage 3 — File size heuristic**: Falls back to file-size-based heuristics
   when earlier stages are inconclusive.

Key differences from the backend version:

* Accepts a file-like object (``BytesIO`` / ``IO[bytes]``) in addition to a
  ``Path``, making it compatible with Streamlit's ``st.file_uploader``.
* Uses ``st.write`` / ``st.warning`` for user-facing feedback when running
  inside Streamlit, while falling back to ``logging`` otherwise.
* All heuristic constants are identical to the backend to guarantee consistent
  classification results.
"""

from __future__ import annotations

import logging
import tempfile
from enum import Enum
from pathlib import Path
from typing import BinaryIO, Optional, Union

import pdfplumber

logger = logging.getLogger(__name__)

# ── Constants ────────────────────────────────────────────────────────────────

# Stage 1: /Image XObject thresholds (images per page)
HIGH_IMAGE_DENSITY: float = 1.5  # >= this many images/page → likely scanned
LOW_IMAGE_DENSITY: float = 0.1  # <= this many images/page → likely digital

# Stage 2: Text extraction sampling
SAMPLE_SIZE: int = 5  # number of pages to sample (first N pages)
MIN_TEXT_LENGTH: int = 50  # minimum chars per sampled page to count as "has text"
TEXT_THRESHOLD_RATIO: float = 0.6  # fraction of sampled pages that must have text

# Stage 3: File size heuristic (bytes)
SCANNED_SIZE_THRESHOLD: int = 200_000  # >= this size → likely scanned
DIGITAL_SIZE_THRESHOLD: int = 50_000  # <= this size → likely digital


class PDFType(Enum):
    """Classification of a PDF document's origin type."""

    DIGITAL = "digital"
    """PDF with a native, selectable text layer (e.g. generated by Word, LaTeX)."""

    SCANNED = "scanned"
    """PDF composed entirely of scanned images with no text layer."""

    HYBRID = "hybrid"
    """PDF containing both selectable text and scanned image pages."""

    UNKNOWN = "unknown"
    """Could not be reliably classified."""


# ── Public API ───────────────────────────────────────────────────────────────


def detect_pdf_type(
    source: Union[Path, str, BinaryIO],
    filename: Optional[str] = None,
) -> PDFType:
    """
    Classify a PDF document as DIGITAL, SCANNED, HYBRID, or UNKNOWN.

    Accepts a file path (``str`` or ``Path``) or a binary file-like object
    (e.g. ``BytesIO`` from ``st.file_uploader``). When a file-like object is
    provided, its content is written to a temporary file so ``pdfplumber`` can
    open it reliably.

    The function runs a three-stage heuristic pipeline:

    1. **Stage 1 — /Image XObject count**: Opens the PDF with ``pdfplumber``
       and counts ``/Image`` XObjects across all pages. A high image-per-page
       density suggests scanned content; a low density suggests digital content.
       If the result is clear-cut, the function returns early.

    2. **Stage 2 — Text extraction sampling**: Samples the first ``SAMPLE_SIZE``
       pages and attempts to extract text via ``pdfplumber``. If a sufficient
       fraction of sampled pages yield meaningful text, the PDF is considered
       digital (or hybrid if Stage 1 indicated images).

    3. **Stage 3 — File size heuristic**: When Stages 1 and 2 are inconclusive,
       falls back to file-size-based heuristics. Large files are likely scanned;
       small files are likely digital.

    Args:
        source: Path to the PDF file, or a binary file-like object containing
            PDF data.
        filename: Optional original filename (used for logging when ``source``
            is a file-like object).

    Returns:
        A :class:`PDFType` enum value indicating the classification.

    Raises:
        FileNotFoundError: If ``source`` is a path and the file does not exist.
        ValueError: If ``source`` is a path that is not a file.
    """
    # ── Resolve to a Path ─────────────────────────────────────────────────
    if isinstance(source, (str, Path)):
        file_path = Path(source)
        if not file_path.exists():
            logger.error("PDF file not found: %s", file_path)
            raise FileNotFoundError(f"PDF file not found: {file_path}")
        if not file_path.is_file():
            logger.error("Path is not a file: %s", file_path)
            raise ValueError(f"Path is not a file: {file_path}")
        return _detect_from_path(file_path)

    # ── File-like object → write to temp file ─────────────────────────────
    label = filename or "uploaded_stream"
    logger.info("Writing uploaded PDF stream (%s) to temporary file", label)
    with tempfile.NamedTemporaryFile(delete=False, suffix=".pdf") as tmp:
        tmp.write(source.read())
        tmp_path = Path(tmp.name)

    try:
        return _detect_from_path(tmp_path)
    finally:
        # Clean up the temporary file
        try:
            tmp_path.unlink(missing_ok=True)
        except OSError:
            logger.warning("Could not remove temporary file: %s", tmp_path)


# ── Internal detection pipeline ──────────────────────────────────────────────


def _detect_from_path(file_path: Path) -> PDFType:
    """
    Run the three-stage detection pipeline against a PDF at *file_path*.

    This is the core pipeline, identical in logic to the backend version.
    """
    logger.info("Starting PDF type detection for: %s", file_path)

    # ── Stage 1: /Image XObject count heuristic ──────────────────────────
    try:
        result = _stage1_image_xobject_count(file_path)
        if result is not None:
            logger.info(
                "Stage 1 (/Image XObject count) decisive: %s",
                result.value,
                extra={"file_path": str(file_path), "pdf_type": result.value},
            )
            return result
    except Exception:
        logger.warning(
            "Stage 1 (/Image XObject count) failed for: %s",
            file_path,
            exc_info=True,
        )

    # ── Stage 2: Text extraction sampling heuristic ──────────────────────
    try:
        result = _stage2_text_extraction_sample(file_path)
        if result is not None:
            logger.info(
                "Stage 2 (text extraction sampling) decisive: %s",
                result.value,
                extra={"file_path": str(file_path), "pdf_type": result.value},
            )
            return result
    except Exception:
        logger.warning(
            "Stage 2 (text extraction sampling) failed for: %s",
            file_path,
            exc_info=True,
        )

    # ── Stage 3: File size heuristic (fallback) ──────────────────────────
    try:
        result = _stage3_file_size_heuristic(file_path)
        logger.info(
            "Stage 3 (file size heuristic) result: %s",
            result.value,
            extra={"file_path": str(file_path), "pdf_type": result.value},
        )
        return result
    except Exception:
        logger.warning(
            "Stage 3 (file size heuristic) failed for: %s",
            file_path,
            exc_info=True,
        )

    # ── All stages failed → UNKNOWN ──────────────────────────────────────
    logger.warning(
        "All detection stages failed for: %s — returning UNKNOWN",
        file_path,
        extra={"file_path": str(file_path), "pdf_type": "unknown"},
    )
    return PDFType.UNKNOWN


# ── Stage 1 ───────────────────────────────────────────────────────────────────


def _stage1_image_xobject_count(file_path: Path) -> Optional[PDFType]:
    """
    Count ``/Image`` XObjects across all pages to estimate image density.

    A high number of images per page strongly suggests a scanned document.
    A very low number suggests a digital document.

    Returns:
        ``PDFType.SCANNED``, ``PDFType.DIGITAL``, or ``None`` if inconclusive.
    """
    logger.debug(
        "Stage 1: Counting /Image XObjects for: %s",
        file_path,
        extra={"file_path": str(file_path)},
    )

    with pdfplumber.open(file_path) as pdf:
        num_pages = len(pdf.pages)
        if num_pages == 0:
            logger.debug(
                "Stage 1: PDF has zero pages — inconclusive",
                extra={"file_path": str(file_path)},
            )
            return None

        total_images = 0
        for page in pdf.pages:
            xobjects = page.xobjects if page.xobjects else []
            image_count = sum(1 for xobj in xobjects if xobj.get("subtype") == "Image")
            total_images += image_count

        images_per_page = total_images / num_pages

        logger.debug(
            "Stage 1: %d images across %d pages (%.2f images/page)",
            total_images,
            num_pages,
            images_per_page,
            extra={
                "file_path": str(file_path),
                "total_images": total_images,
                "num_pages": num_pages,
                "images_per_page": images_per_page,
            },
        )

        if images_per_page >= HIGH_IMAGE_DENSITY:
            logger.debug(
                "Stage 1: High image density (%.2f >= %.2f) → SCANNED",
                images_per_page,
                HIGH_IMAGE_DENSITY,
                extra={"file_path": str(file_path)},
            )
            return PDFType.SCANNED

        if images_per_page <= LOW_IMAGE_DENSITY:
            logger.debug(
                "Stage 1: Low image density (%.2f <= %.2f) → DIGITAL",
                images_per_page,
                LOW_IMAGE_DENSITY,
                extra={"file_path": str(file_path)},
            )
            return PDFType.DIGITAL

        # Inconclusive — return None so the caller proceeds to Stage 2.
        logger.debug(
            "Stage 1: Inconclusive (%.2f images/page) — proceeding to Stage 2",
            images_per_page,
            extra={
                "file_path": str(file_path),
                "images_per_page": images_per_page,
            },
        )
        return None


# ── Stage 2 ───────────────────────────────────────────────────────────────────


def _stage2_text_extraction_sample(file_path: Path) -> Optional[PDFType]:
    """
    Sample the first N pages and attempt text extraction.

    If a sufficient fraction of sampled pages yield meaningful text, the PDF
    is classified as digital (or hybrid if Stage 1 indicated images).

    Returns:
        ``PDFType.DIGITAL``, ``PDFType.HYBRID``, or ``None`` if inconclusive.
    """
    logger.debug(
        "Stage 2: Sampling text extraction for: %s",
        file_path,
        extra={"file_path": str(file_path)},
    )

    with pdfplumber.open(file_path) as pdf:
        num_pages = len(pdf.pages)
        if num_pages == 0:
            logger.debug(
                "Stage 2: PDF has zero pages — inconclusive",
                extra={"file_path": str(file_path)},
            )
            return None

        pages_to_sample = min(SAMPLE_SIZE, num_pages)
        pages_with_text = 0

        for i in range(pages_to_sample):
            page = pdf.pages[i]
            text = page.extract_text() or ""
            text_length = len(text.strip())

            if text_length >= MIN_TEXT_LENGTH:
                pages_with_text += 1

            logger.debug(
                "Stage 2: Page %d/%d — extracted %d chars",
                i + 1,
                pages_to_sample,
                text_length,
                extra={
                    "file_path": str(file_path),
                    "page": i + 1,
                    "text_length": text_length,
                },
            )

        text_ratio = pages_with_text / pages_to_sample

        logger.debug(
            "Stage 2: %d/%d sampled pages have text (ratio=%.2f)",
            pages_with_text,
            pages_to_sample,
            text_ratio,
            extra={
                "file_path": str(file_path),
                "pages_with_text": pages_with_text,
                "pages_sampled": pages_to_sample,
                "text_ratio": text_ratio,
            },
        )

        if text_ratio >= TEXT_THRESHOLD_RATIO:
            # Most sampled pages have text — likely digital or hybrid.
            # Re-run Stage 1's image check to distinguish hybrid from digital.
            if _has_significant_images(file_path):
                logger.debug(
                    "Stage 2: High text ratio (%.2f) + significant images → HYBRID",
                    text_ratio,
                    extra={"file_path": str(file_path)},
                )
                return PDFType.HYBRID

            logger.debug(
                "Stage 2: High text ratio (%.2f) + few images → DIGITAL",
                text_ratio,
                extra={"file_path": str(file_path)},
            )
            return PDFType.DIGITAL

        # Low text ratio — likely scanned, but could be an image-heavy digital PDF.
        # Return None so Stage 3 (file size) can disambiguate.
        logger.debug(
            "Stage 2: Low text ratio (%.2f) — inconclusive, proceeding to Stage 3",
            text_ratio,
            extra={"file_path": str(file_path), "text_ratio": text_ratio},
        )
        return None


def _has_significant_images(file_path: Path) -> bool:
    """
    Quick check whether the PDF contains a meaningful number of images.

    Used by Stage 2 to distinguish ``HYBRID`` from ``DIGITAL`` when text
    extraction succeeds on most pages.

    Returns:
        ``True`` if the image density exceeds ``LOW_IMAGE_DENSITY``.
    """
    try:
        with pdfplumber.open(file_path) as pdf:
            num_pages = len(pdf.pages)
            if num_pages == 0:
                return False

            total_images = 0
            for page in pdf.pages:
                xobjects = page.xobjects if page.xobjects else []
                total_images += sum(
                    1 for xobj in xobjects if xobj.get("subtype") == "Image"
                )

            images_per_page = total_images / num_pages
            return images_per_page > LOW_IMAGE_DENSITY
    except Exception:
        logger.debug(
            "Image check failed for: %s — assuming no significant images",
            file_path,
            exc_info=True,
        )
        return False


# ── Stage 3 ───────────────────────────────────────────────────────────────────


def _stage3_file_size_heuristic(file_path: Path) -> PDFType:
    """
    Fallback heuristic based on file size.

    Scanned PDFs tend to be large (each page is a compressed image).
    Digital PDFs tend to be smaller (text + fonts).

    Returns:
        ``PDFType.SCANNED``, ``PDFType.DIGITAL``, or ``PDFType.UNKNOWN``.
    """
    file_size = file_path.stat().st_size

    logger.debug(
        "Stage 3: File size heuristic for: %s (%d bytes)",
        file_path,
        file_size,
        extra={"file_path": str(file_path), "file_size": file_size},
    )

    if file_size >= SCANNED_SIZE_THRESHOLD:
        logger.debug(
            "Stage 3: File size %d >= %d → SCANNED",
            file_size,
            SCANNED_SIZE_THRESHOLD,
            extra={"file_path": str(file_path)},
        )
        return PDFType.SCANNED

    if file_size <= DIGITAL_SIZE_THRESHOLD:
        logger.debug(
            "Stage 3: File size %d <= %d → DIGITAL",
            file_size,
            DIGITAL_SIZE_THRESHOLD,
            extra={"file_path": str(file_path)},
        )
        return PDFType.DIGITAL

    # File size falls in the ambiguous middle range.
    logger.debug(
        "Stage 3: File size %d in ambiguous range — returning UNKNOWN",
        file_size,
        extra={"file_path": str(file_path)},
    )
    return PDFType.UNKNOWN
